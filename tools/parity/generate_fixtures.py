"""Generates scikit-learn reference fixtures for the parity tests.

Run offline, once, when the fixtures need regenerating. The generated files are
committed, so CI never needs scikit-learn for correctness.

    python tools/parity/generate_fixtures.py

The script refuses to run against any scikit-learn version other than PINNED.
Changing the pin is a deliberate act: regenerate, review the diff, and commit.

File format (one `key values...` pair per line, `#` for comments):

    kind kmeans | pca
    rows N / cols D / k K (or n_components)
    x      <N*D values, row-major>
    init   <K*D values>                       (kmeans only: explicit starting centres)
    centers <K*D values>                      (kmeans only)
    labels <N ints>                           (kmeans only)
    inertia <value>                           (kmeans only)
    n_iter <value>                            (kmeans only)
    mean   <D values>                         (pca only)
    components <K*D values, row-major>        (pca only)
    explained_variance <K values>             (pca only)
    explained_variance_ratio <K values>       (pca only)

Values are written with 17 significant digits, so they round-trip through f64.
"""

from pathlib import Path

import numpy as np
import sklearn
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA

PINNED = "1.9.0"
OUT = Path(__file__).resolve().parent / "fixtures"


def fmt(values):
    return " ".join(f"{float(v):.17g}" for v in np.ravel(values))


def write(name, header, fields):
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# generated by tools/parity/generate_fixtures.py; do not edit by hand"]
    lines.append(f"# scikit-learn {sklearn.__version__}")
    lines += [f"{key} {value}" for key, value in header]
    lines += [f"{key} {value}" for key, value in fields]
    (OUT / f"{name}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {name}.txt")


def kmeans_case(name, x, k, seed):
    rng = np.random.default_rng(seed)
    # Explicit starting centres: k distinct rows, so both implementations start
    # from exactly the same point. This isolates the Lloyd iteration from the
    # initialisation RNG, which differs between implementations.
    init = x[rng.choice(len(x), size=k, replace=False)]
    model = KMeans(
        n_clusters=k,
        init=init,
        n_init=1,
        algorithm="lloyd",
        tol=0.0,
        max_iter=1000,
    ).fit(x)
    if len(np.unique(model.labels_)) != k:
        raise SystemExit(f"{name}: scikit-learn left an empty cluster; pick another seed")
    write(
        name,
        [("kind", "kmeans"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("k", k)],
        [
            ("x", fmt(x)),
            ("init", fmt(init)),
            ("centers", fmt(model.cluster_centers_)),
            ("labels", " ".join(str(int(v)) for v in model.labels_)),
            ("inertia", f"{float(model.inertia_):.17g}"),
            ("n_iter", int(model.n_iter_)),
        ],
    )


def pca_case(name, x, k):
    model = PCA(n_components=k, svd_solver="full").fit(x)
    write(
        name,
        [("kind", "pca"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("n_components", k)],
        [
            ("x", fmt(x)),
            ("mean", fmt(model.mean_)),
            ("components", fmt(model.components_)),
            ("explained_variance", fmt(model.explained_variance_)),
            ("explained_variance_ratio", fmt(model.explained_variance_ratio_)),
        ],
    )


def main():
    if sklearn.__version__ != PINNED:
        raise SystemExit(
            f"scikit-learn {sklearn.__version__} installed, but the pin is {PINNED}"
        )

    rng = np.random.default_rng(20260101)

    # KMeans: well-separated blobs, a uniform cloud, and the k = 1 edge case.
    centres = np.array([[0.0, 0.0, 0.0], [6.0, 0.0, 1.0], [0.0, 6.0, -2.0], [6.0, 6.0, 3.0]])
    blobs = np.vstack([c + 0.6 * rng.standard_normal((50, 3)) for c in centres])
    kmeans_case("kmeans_blobs_k4", blobs, 4, seed=1)
    kmeans_case("kmeans_uniform_k5", rng.uniform(-3, 3, size=(120, 4)), 5, seed=2)
    kmeans_case("kmeans_one_cluster", rng.standard_normal((40, 2)), 1, seed=3)

    # PCA: correlated data (rank 5, so the full decomposition is interesting) and
    # a truncated one.
    mixing = rng.standard_normal((5, 5))
    correlated = rng.standard_normal((80, 5)) @ mixing
    pca_case("pca_correlated_full", correlated, 5)
    pca_case("pca_correlated_k3", correlated, 3)


if __name__ == "__main__":
    main()
