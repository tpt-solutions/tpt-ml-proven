"""Generates scikit-learn reference fixtures for the parity tests.

Run offline, once, when the fixtures need regenerating. The generated files are
committed, so CI never needs scikit-learn for correctness.

    python tools/parity/generate_fixtures.py

The script refuses to run against any scikit-learn version other than PINNED.
Changing the pin is a deliberate act: regenerate, review the diff, and commit.

File format (one `key values...` pair per line, `#` for comments):

    kind kmeans | pca
    rows N / cols D / k K (or n_components)
    x      <N*D values, row-major>
    init   <K*D values>                       (kmeans only: explicit starting centres)
    centers <K*D values>                      (kmeans only)
    labels <N ints>                           (kmeans only)
    inertia <value>                           (kmeans only)
    n_iter <value>                            (kmeans only)
    mean   <D values>                         (pca only)
    components <K*D values, row-major>        (pca only)
    explained_variance <K values>             (pca only)
    explained_variance_ratio <K values>       (pca only)

Values are written with 17 significant digits, so they round-trip through f64.
"""

from pathlib import Path

import numpy as np
import sklearn
from sklearn.cluster import DBSCAN, HDBSCAN, KMeans
from sklearn.linear_model import ElasticNet, Lasso, LogisticRegression, Ridge
from sklearn.decomposition import NMF, PCA, TruncatedSVD
from sklearn.preprocessing import MinMaxScaler, RobustScaler, StandardScaler
from sklearn.ensemble import GradientBoostingRegressor

PINNED = "1.9.0"
OUT = Path(__file__).resolve().parent / "fixtures"


def fmt(values):
    return " ".join(f"{float(v):.17g}" for v in np.ravel(values))


def write(name, header, fields):
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# generated by tools/parity/generate_fixtures.py; do not edit by hand"]
    lines.append(f"# scikit-learn {sklearn.__version__}")
    lines += [f"{key} {value}" for key, value in header]
    lines += [f"{key} {value}" for key, value in fields]
    (OUT / f"{name}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {name}.txt")


def kmeans_case(name, x, k, seed):
    rng = np.random.default_rng(seed)
    # Explicit starting centres: k distinct rows, so both implementations start
    # from exactly the same point. This isolates the Lloyd iteration from the
    # initialisation RNG, which differs between implementations.
    init = x[rng.choice(len(x), size=k, replace=False)]
    model = KMeans(
        n_clusters=k,
        init=init,
        n_init=1,
        algorithm="lloyd",
        tol=0.0,
        max_iter=1000,
    ).fit(x)
    if len(np.unique(model.labels_)) != k:
        raise SystemExit(f"{name}: scikit-learn left an empty cluster; pick another seed")
    write(
        name,
        [("kind", "kmeans"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("k", k)],
        [
            ("x", fmt(x)),
            ("init", fmt(init)),
            ("centers", fmt(model.cluster_centers_)),
            ("labels", " ".join(str(int(v)) for v in model.labels_)),
            ("inertia", f"{float(model.inertia_):.17g}"),
            ("n_iter", int(model.n_iter_)),
        ],
    )


def pca_case(name, x, k):
    model = PCA(n_components=k, svd_solver="full").fit(x)
    write(
        name,
        [("kind", "pca"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("n_components", k)],
        [
            ("x", fmt(x)),
            ("mean", fmt(model.mean_)),
            ("components", fmt(model.components_)),
            ("explained_variance", fmt(model.explained_variance_)),
            ("explained_variance_ratio", fmt(model.explained_variance_ratio_)),
        ],
    )


def dbscan_case(name, x, eps, min_samples):
    model = DBSCAN(eps=eps, min_samples=min_samples, algorithm="brute").fit(x)
    write(
        name,
        [("kind", "dbscan"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("eps", f"{eps:.17g}"), ("min_samples", min_samples)],
        [
            ("x", fmt(x)),
            ("labels", " ".join(str(int(v)) for v in model.labels_)),
            ("core", " ".join(str(int(v)) for v in model.core_sample_indices_)),
        ],
    )


def linear_case(name, model, x, y, params):
    model.fit(x, y)
    write(
        name,
        [("kind", "linear"), ("model", params["model"]), ("rows", x.shape[0]), ("cols", x.shape[1]), ("alpha", f"{params['alpha']:.17g}"), ("l1_ratio", f"{params.get('l1_ratio', 0.0):.17g}")],
        [
            ("x", fmt(x)),
            ("y", fmt(y)),
            ("coef", fmt(model.coef_)),
            ("intercept", f"{float(model.intercept_):.17g}"),
        ],
    )


def logistic_case(name, x, y, c):
    model = LogisticRegression(C=c, solver="lbfgs", tol=1e-12, max_iter=10000).fit(x, y)
    write(
        name,
        [("kind", "logistic"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("C", f"{c:.17g}")],
        [
            ("x", fmt(x)),
            ("y", fmt(y)),
            ("coef", fmt(model.coef_[0])),
            ("intercept", f"{float(model.intercept_[0]):.17g}"),
            ("proba", fmt(model.predict_proba(x)[:, 1])),
        ],
    )


def scaler_case(name, x):
    # Each scaler is fitted on x and asked to transform x, so the fixture holds the
    # fitted statistics and the transformed output for both sides to compare.
    standard = StandardScaler().fit(x)
    minmax = MinMaxScaler().fit(x)
    robust = RobustScaler().fit(x)
    write(
        name,
        [("kind", "scaler"), ("rows", x.shape[0]), ("cols", x.shape[1])],
        [
            ("x", fmt(x)),
            ("standard_mean", fmt(standard.mean_)),
            ("standard_scale", fmt(standard.scale_)),
            ("standard_out", fmt(standard.transform(x))),
            ("minmax_min", fmt(minmax.min_)),
            ("minmax_scale", fmt(minmax.scale_)),
            ("minmax_out", fmt(minmax.transform(x))),
            ("robust_center", fmt(robust.center_)),
            ("robust_scale", fmt(robust.scale_)),
            ("robust_out", fmt(robust.transform(x))),
        ],
    )


def nmf_case(name, x, k, init_w, init_h, max_iter, tol):
    # Explicit starting factors, multiplicative updates, Frobenius loss.
    model = NMF(
        n_components=k,
        init="custom",
        solver="mu",
        beta_loss="frobenius",
        max_iter=max_iter,
        tol=tol,
    )
    w = model.fit_transform(x, W=init_w.copy(), H=init_h.copy())
    write(
        name,
        [("kind", "nmf"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("k", k), ("tol", f"{tol:.17g}"), ("max_iter", max_iter)],
        [
            ("x", fmt(x)),
            ("init_w", fmt(init_w)),
            ("init_h", fmt(init_h)),
            ("w", fmt(w)),
            ("h", fmt(model.components_)),
            ("n_iter", int(model.n_iter_)),
        ],
    )


def hdbscan_case(name, x, min_cluster_size):
    model = HDBSCAN(min_cluster_size=min_cluster_size, cluster_selection_method="eom", allow_single_cluster=False, algorithm="brute", copy=False).fit(x)
    write(
        name,
        [("kind", "hdbscan"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("min_cluster_size", min_cluster_size)],
        [
            ("x", fmt(x)),
            ("labels", " ".join(str(int(v)) for v in model.labels_)),
        ],
    )


def multiclass_logistic_case(name, x, y, c):
    model = LogisticRegression(C=c, solver="lbfgs", tol=1e-12, max_iter=10000).fit(x, y)
    write(
        name,
        [("kind", "logistic_multi"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("classes", len(model.classes_)), ("C", f"{c:.17g}")],
        [
            ("x", fmt(x)),
            ("y", fmt(y)),
            ("coef", fmt(model.coef_)),
            ("proba", fmt(model.predict_proba(x))),
        ],
    )


def gbm_case(name, x, y, n_estimators, learning_rate, max_depth, min_samples_leaf):
    model = GradientBoostingRegressor(
        n_estimators=n_estimators,
        learning_rate=learning_rate,
        max_depth=max_depth,
        min_samples_leaf=min_samples_leaf,
        criterion="friedman_mse",
        subsample=1.0,
        random_state=0,
    ).fit(x, y)
    write(
        name,
        [("kind", "gbm"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("n_estimators", n_estimators),
         ("learning_rate", f"{learning_rate:.17g}"), ("max_depth", max_depth), ("min_samples_leaf", min_samples_leaf)],
        [
            ("x", fmt(x)),
            ("y", fmt(y)),
            ("pred", fmt(model.predict(x))),
        ],
    )


def svd_case(name, x, k):
    model = TruncatedSVD(n_components=k, algorithm="arpack", random_state=0).fit(x)
    write(
        name,
        [("kind", "svd"), ("rows", x.shape[0]), ("cols", x.shape[1]), ("n_components", k)],
        [
            ("x", fmt(x)),
            ("singular_values", fmt(model.singular_values_)),
            ("components", fmt(model.components_)),
        ],
    )


def main():
    if sklearn.__version__ != PINNED:
        raise SystemExit(
            f"scikit-learn {sklearn.__version__} installed, but the pin is {PINNED}"
        )

    rng = np.random.default_rng(20260101)

    # KMeans: well-separated blobs, a uniform cloud, and the k = 1 edge case.
    centres = np.array([[0.0, 0.0, 0.0], [6.0, 0.0, 1.0], [0.0, 6.0, -2.0], [6.0, 6.0, 3.0]])
    blobs = np.vstack([c + 0.6 * rng.standard_normal((50, 3)) for c in centres])
    kmeans_case("kmeans_blobs_k4", blobs, 4, seed=1)
    kmeans_case("kmeans_uniform_k5", rng.uniform(-3, 3, size=(120, 4)), 5, seed=2)
    kmeans_case("kmeans_one_cluster", rng.standard_normal((40, 2)), 1, seed=3)

    # PCA: correlated data (rank 5, so the full decomposition is interesting) and
    # a truncated one.
    mixing = rng.standard_normal((5, 5))
    correlated = rng.standard_normal((80, 5)) @ mixing
    pca_case("pca_correlated_full", correlated, 5)
    pca_case("pca_correlated_k3", correlated, 3)

    # DBSCAN: separate rng so the fixtures above are unchanged.
    rng2 = np.random.default_rng(777)
    groups = np.vstack([c + 0.25 * rng2.standard_normal((40, 2)) for c in [np.array([0.0, 0.0]), np.array([3.0, 3.0]), np.array([0.0, 4.0])]])
    noise = rng2.uniform(-2, 6, size=(12, 2))
    dbscan_case("dbscan_blobs_noise", np.vstack([groups, noise]), eps=0.6, min_samples=5)

    # TruncatedSVD on uncentred data.
    svd_x = correlated + 1.5
    svd_case("svd_arpack_k2", svd_x, 2)

    # Linear models: a noisy linear target, with its own rng.
    rng3 = np.random.default_rng(4242)
    xr = rng3.standard_normal((60, 4))
    yr = xr @ np.array([1.5, -2.0, 0.0, 0.5]) + 0.3 + 0.1 * rng3.standard_normal(60)
    linear_case("linear_ridge", Ridge(alpha=1.0), xr, yr, {"model": "ridge", "alpha": 1.0})
    linear_case("linear_lasso", Lasso(alpha=0.05, tol=1e-12, max_iter=100000), xr, yr, {"model": "lasso", "alpha": 0.05})
    linear_case("linear_elasticnet", ElasticNet(alpha=0.05, l1_ratio=0.5, tol=1e-12, max_iter=100000), xr, yr, {"model": "elasticnet", "alpha": 0.05, "l1_ratio": 0.5})

    # Logistic regression: a binary target from a noisy linear score, with its own rng.
    rng4 = np.random.default_rng(9001)
    xl = rng4.standard_normal((80, 3))
    score = xl @ np.array([2.0, -1.0, 0.5]) - 0.2 + 0.5 * rng4.standard_normal(80)
    yl = (score > 0).astype(float)
    logistic_case("logistic_binary_c1", xl, yl, c=1.0)

    # Scalers: skewed, offset columns with an outlier, so the robust statistics differ
    # from the mean and standard deviation. Own rng.
    rng5 = np.random.default_rng(55)
    xs = np.column_stack([
        3.0 + 2.0 * rng5.standard_normal(30),
        np.exp(rng5.standard_normal(30)),
        rng5.uniform(-10, 10, 30),
    ])
    xs[0, 2] = 250.0
    scaler_case("scalers_skewed", xs)

    # NMF: non-negative data with two latent sources, explicit starting factors.
    rng6 = np.random.default_rng(31)
    sources = rng6.uniform(0, 1, size=(30, 2))
    mixing_nmf = rng6.uniform(0, 1, size=(2, 5))
    xn = sources @ mixing_nmf + 0.01 * rng6.uniform(0, 1, size=(30, 5))
    k_nmf = 2
    w0 = rng6.uniform(0.1, 1.0, size=(30, k_nmf))
    h0 = rng6.uniform(0.1, 1.0, size=(k_nmf, 5))
    nmf_case("nmf_mu_fixed_iters", xn, k_nmf, w0, h0, max_iter=60, tol=0.0)
    nmf_case("nmf_mu_tol", xn, k_nmf, w0, h0, max_iter=500, tol=1e-4)

    # HDBSCAN: three blobs of different density, plus scattered noise. Own rng.
    rng7 = np.random.default_rng(2024)
    blobs_h = np.vstack([
        np.array([0.0, 0.0]) + 0.2 * rng7.standard_normal((40, 2)),
        np.array([4.0, 0.0]) + 0.5 * rng7.standard_normal((40, 2)),
        np.array([0.0, 5.0]) + 0.3 * rng7.standard_normal((40, 2)),
    ])
    noise_h = rng7.uniform(-3, 7, size=(10, 2))
    hdbscan_case("hdbscan_blobs_noise", np.vstack([blobs_h, noise_h]), min_cluster_size=8)

    # Multiclass logistic: three classes from noisy linear scores. Own rng.
    rng8 = np.random.default_rng(777001)
    xm = rng8.standard_normal((90, 2))
    scores = xm @ np.array([[1.5, -1.0, 0.2], [-0.5, 1.2, 0.8]]) + 0.3 * rng8.standard_normal((90, 3))
    ym = scores.argmax(axis=1).astype(float)
    multiclass_logistic_case("logistic_multiclass_c1", xm, ym, c=1.0)

    # Gradient boosting: a nonlinear target with noise. Own rng.
    rng9 = np.random.default_rng(606)
    xg = rng9.uniform(-3, 3, size=(120, 3))
    yg = np.sin(xg[:, 0]) * 2 + (xg[:, 1] > 0.5) * 1.5 - 0.3 * xg[:, 2] + 0.2 * rng9.standard_normal(120)
    gbm_case("gbm_regression", xg, yg, n_estimators=30, learning_rate=0.1, max_depth=3, min_samples_leaf=2)


if __name__ == "__main__":
    main()
